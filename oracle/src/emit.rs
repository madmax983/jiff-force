//! Writes vectors as Apex "data classes": `@IsTest` classes whose only job is
//! to return rows of pipe separated text for a hand written test to check.

use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use anyhow::{Context, Result};

/// Apex caps the size of a single method, so rows are split across several.
const ROWS_PER_METHOD: usize = 200;

/// Renders and writes `JiffOracle<topic>Data.cls` into `classes_dir`.
pub fn write_data_class(
    classes_dir: &Path,
    topic: &str,
    columns: &str,
    rows: &[String],
) -> Result<()> {
    let name = format!("JiffOracle{topic}Data");
    let source = render(&name, columns, rows);
    let path = classes_dir.join(format!("{name}.cls"));
    fs::write(&path, source).with_context(|| format!("writing {}", path.display()))?;
    println!("{name}: {} rows", rows.len());
    Ok(())
}

fn render(name: &str, columns: &str, rows: &[String]) -> String {
    let chunks: Vec<&[String]> = rows.chunks(ROWS_PER_METHOD).collect();
    let mut out = String::new();
    // Writing to a String cannot fail, so the results are discarded.
    let _ = writeln!(out, "/**");
    let _ = writeln!(
        out,
        " * GENERATED by `oracle/` from jiff {}. Do not edit by hand.",
        jiff_version()
    );
    let _ = writeln!(out, " * Regenerate with `npm run oracle`.");
    let _ = writeln!(out, " *");
    let _ = writeln!(out, " * Each row is: {columns}");
    let _ = writeln!(out, " */");
    let _ = writeln!(out, "@IsTest");
    let _ = writeln!(out, "public class {name} {{");
    let _ = writeln!(out, "    public static List<String> rows() {{");
    let _ = writeln!(out, "        List<String> all = new List<String>();");
    for index in 0..chunks.len() {
        let _ = writeln!(out, "        all.addAll(chunk{index}());");
    }
    let _ = writeln!(out, "        return all;");
    let _ = writeln!(out, "    }}");
    for (index, chunk) in chunks.iter().enumerate() {
        let _ = writeln!(out);
        let _ = writeln!(out, "    private static List<String> chunk{index}() {{");
        let _ = writeln!(out, "        return new List<String>{{");
        for (i, row) in chunk.iter().enumerate() {
            let comma = if i + 1 == chunk.len() { "" } else { "," };
            let _ = writeln!(out, "            '{}'{comma}", escape(row));
        }
        let _ = writeln!(out, "        }};");
        let _ = writeln!(out, "    }}");
    }
    let _ = writeln!(out, "}}");
    out
}

/// Escapes a row for use inside a single quoted Apex string literal.
fn escape(row: &str) -> String {
    row.replace('\\', "\\\\").replace('\'', "\\'")
}

/// The Jiff release the vectors were generated from.
pub const fn jiff_version() -> &'static str {
    "1.0.0"
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn escapes_quotes_and_backslashes() {
        assert_eq!(escape(r"it's a \ test"), r"it\'s a \\ test");
    }

    #[test]
    fn splits_rows_across_methods() {
        let rows: Vec<String> = (0..=ROWS_PER_METHOD).map(|i| i.to_string()).collect();
        let source = render("JiffOracleDemoData", "n", &rows);
        assert!(source.contains("all.addAll(chunk0());"));
        assert!(source.contains("all.addAll(chunk1());"));
        assert!(source.contains("private static List<String> chunk1()"));
        assert!(!source.contains("chunk2"));
    }

    #[test]
    fn renders_a_class_with_no_trailing_comma() {
        let source = render(
            "JiffOracleDemoData",
            "a|b",
            &["1|2".to_owned(), "3|4".to_owned()],
        );
        assert!(source.contains("'1|2',\n"));
        assert!(source.contains("'3|4'\n"));
        assert!(source.contains("public class JiffOracleDemoData {"));
    }
}
